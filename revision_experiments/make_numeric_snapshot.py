#!/usr/bin/env python
"""Regenerate the pre-humanize numeric/reference snapshot of docs/draft.md (AC-8).

Extracts every numeric token, Supplementary \\ref, citation short-name, and explicit
caveat phrase so a later humanize rewrite can be diffed against this frozen snapshot to
detect accidental numeric/reference/caveat drift. Run after any change to docs/draft.md
numbers.

Usage:  python make_numeric_snapshot.py
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
DRAFT = os.path.join(HERE, "..", "docs", "draft.md")
OUT = os.path.join(HERE, "..", "docs", "draft_numeric_snapshot.txt")

# numeric token: optional sign (ASCII - or U+2212), digits with thousands commas and
# optional decimal, optionally followed by a "± sd" companion.
NUM = re.compile(r"[−-]?\d[\d,]*(?:\.\d+)?(?:\s*±\s*\d+(?:\.\d+)?)?")
REF = re.compile(r"\\ref\{[^}]+\}")
CITES = ["UnCOT-AD", "CFM-GP", "DCGAT-DTI", "LOCAS", "GTG-ACO", "RNA-EFM", "DeepRNA-Twist"]
CAVEATS = ["lower-bound proxy", "partly definitional", "single seed", "single-seed",
           "298 observations", "3,735 observations", "small sparse stress test"]


def _num_key(s):
    return abs(float(s.split("±")[0].replace(",", "").replace("−", "-").strip()))


def main():
    text = open(DRAFT, encoding="utf-8").read()
    nums = sorted(set(m.group(0).strip() for m in NUM.finditer(text)), key=_num_key)
    refs = sorted(set(REF.findall(text)))
    cites = [c for c in CITES if c in text]
    caveats = [c for c in CAVEATS if c in text]

    lines = [
        "# Pre-humanize numeric/reference snapshot of docs/draft.md",
        "# (AC-8) Diff against a regenerated snapshot after the humanize pass to detect drift.",
        "# Regenerated by revision_experiments/make_numeric_snapshot.py after the Round-2",
        "# fixed-K=511 InfoNCE rerun (R1.1 latent 0.619/0.613, projector 0.768/0.269).",
        "",
        f"## NUMBERS ({len(nums)})",
        *nums,
        "",
        f"## SUPPLEMENTARY REFS ({len(refs)})",
        *refs,
        "",
        f"## CITATION SHORT-NAMES ({len(cites)})",
        *sorted(cites),
        "",
        f"## CAVEATS / DISCLOSURES ({len(caveats)})",
        *caveats,
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(OUT, os.path.join(HERE, "..")),
          f"({len(nums)} numbers, {len(refs)} refs, {len(cites)} cites, {len(caveats)} caveats)")


if __name__ == "__main__":
    main()
