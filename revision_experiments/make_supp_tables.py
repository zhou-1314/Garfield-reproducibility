#!/usr/bin/env python
"""Generate the Supplementary ablation / sensitivity LaTeX tables from the committed
result CSVs, so the tables the rebuttal points reviewers to actually exist in the
manuscript and stay reproducible (no transcription drift).

Emits into Garfield_latex/:
  supp_ablation_table.tex  (tab:ablation)  — module ablation, 10x + hippocampus, 2 seeds
  supp_nsam_table.tex      (tab:nsam)      — neighbour-sampling n_sam sweep, single seed
  supp_svdq_table.tex      (tab:svdq)      — ApproxSVD rank q sweep (dense + sparse), single seed
  supp_lambda_table.tex    (tab:lambda)    — loss-weight x0.1/x10 robustness, single seed
  supp_mmd_table.tex       (tab:mmd)       — MMD batch-alignment ablation, single seed

Usage:  python make_supp_tables.py
"""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
OUT = os.path.join(HERE, "..", "Garfield_latex")


def summary(fname):
    return {r["tag"]: r for r in csv.DictReader(open(os.path.join(RES, fname)))}


def rowval(fname, col):
    r = list(csv.DictReader(open(os.path.join(RES, fname))))
    return float(r[0][col])


def ms(d, metric):
    return f"{float(d[metric+'_mean']):.3f}$\\pm${float(d[metric+'_std']):.3f}"


def write(name, lines):
    with open(os.path.join(OUT, name), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", name)


def ablation_table():
    b = summary("brain10x_abl_summary_2seed.csv")
    h = summary("hippo_abl_summary_2seed.csv")
    order = [("baseline", "Full model"),
             ("no_gene_recon", "$-$ feature reconstruction"),
             ("no_cluster_loss", "$-$ cluster contrastive"),
             ("no_edge_recon", "$-$ edge reconstruction"),
             ("no_contrastive", "$-$ contrastive (instance+cluster)"),
             ("no_entropy_HY", "$-$ clustering entropy $H(Y)$"),
             ("no_adj_recon", "$-$ latent adjacency reconstruction"),
             ("no_instance_loss", "$-$ instance loss")]
    L = ["% Auto-generated by make_supp_tables.py (R1.2/R2.C1/R3.2)",
         "\\begin{table}[ht]", "\\centering",
         "\\caption{\\textbf{\\revised{Module-level ablation of Garfield's loss terms.}} "
         "\\revised{Each term is removed in turn (all else fixed). 10x Multiome mouse brain "
         "(10{,}647 observations, real cell-type labels) and Slide-seqV2 hippocampus "
         "(41{,}786 observations, niche labels); mean$\\pm$s.d. over two seeds \\{2024, 2025\\}. "
         "ASW = cluster average silhouette width; spatial coh.\\ = fraction of spatial "
         "neighbours sharing the predicted cluster.}}",
         "\\label{tab:ablation}", "\\footnotesize",
         "\\begin{tabular}{@{}lccccc@{}}", "\\toprule",
         "\\textbf{Variant} & \\multicolumn{2}{c}{\\textbf{10x Multiome}} & "
         "\\multicolumn{3}{c}{\\textbf{Slide-seqV2 hippocampus}} \\\\",
         "\\cmidrule(lr){2-3}\\cmidrule(lr){4-6}",
         " & ARI & NMI & ASW & spatial coh. & niche ARI \\\\", "\\midrule"]
    for tag, name in order:
        L.append(" & ".join([name, ms(b[tag], "ARI"), ms(b[tag], "NMI"),
                             ms(h[tag], "ASW_cluster"), ms(h[tag], "spatial_coherence"),
                             ms(h[tag], "niches_ARI_bestres")]) + " \\\\")
        if tag == "baseline":
            L.append("\\midrule")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write("supp_ablation_table.tex", L)


def nsam_table():
    hippo = {r["tag"]: r for r in csv.DictReader(open(os.path.join(RES, "rows_dev/hippo_nsam.csv")))}
    L = ["% Auto-generated by make_supp_tables.py (R2.B2)",
         "\\begin{table}[ht]", "\\centering",
         "\\caption{\\textbf{\\revised{Sensitivity to the message-passing neighbour-sampling "
         "parameter $n_{\\mathrm{sam}}$ (= \\texttt{num\\_neighbors}).}} \\revised{10x Multiome "
         "mouse brain (real cell-type labels) and a Slide-seqV2 hippocampus subset "
         "(3{,}735 observations, niche\\_type labels). Single seed (2024); peak GPU is for 10x. "
         "Default $n_{\\mathrm{sam}}=3$.}}",
         "\\label{tab:nsam}", "\\footnotesize",
         "\\begin{tabular}{@{}cccccc@{}}", "\\toprule",
         "$n_{\\mathrm{sam}}$ & \\multicolumn{3}{c}{\\textbf{10x Multiome}} & "
         "\\multicolumn{2}{c}{\\textbf{Hippocampus subset}} \\\\",
         "\\cmidrule(lr){2-4}\\cmidrule(lr){5-6}",
         " & ARI & NMI & peak GPU (GB) & ARI & NMI \\\\", "\\midrule"]
    for k in [1, 3, 5, 10, 15]:
        f = f"rows/brain10x__nsam_{k}__s2024.csv"
        hi = hippo[f"nsam_{k}"]
        nm = f"\\textbf{{{k}}}" if k == 3 else str(k)
        L.append(" & ".join([nm,
                             f"{rowval(f,'ARI'):.3f}", f"{rowval(f,'NMI'):.3f}", f"{rowval(f,'peak_gpu_gb'):.2f}",
                             f"{float(hi['ARI']):.3f}", f"{float(hi['NMI']):.3f}"]) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write("supp_nsam_table.tex", L)


def svdq_table():
    sp = {r["tag"]: r for r in csv.DictReader(open(os.path.join(RES, "rows_dev/hippo_sparse_svdq.csv")))}
    L = ["% Auto-generated by make_supp_tables.py (R2.B3)",
         "\\begin{table}[ht]", "\\centering",
         "\\caption{\\textbf{\\revised{Sensitivity to the ApproxSVD rank $q$.}} \\revised{Dense "
         "10x Multiome mouse brain (real cell-type labels) and an artificially sparsified "
         "Slide-seqV2 hippocampus stress test (298 observations, $\\approx$65\\% read depth). "
         "Single seed (2024); default $q=5$. On the small sparse subset the best-resolution "
         "Leiden partition is quantized, so ARI/NMI are nearly flat while the continuous "
         "embedding silhouette (ASW) varies smoothly with $q$.}}",
         "\\label{tab:svdq}", "\\footnotesize",
         "\\begin{tabular}{@{}ccccccc@{}}", "\\toprule",
         "$q$ & \\multicolumn{2}{c}{\\textbf{10x Multiome (dense)}} & "
         "\\multicolumn{3}{c}{\\textbf{Hippocampus (sparse, $n=298$)}} \\\\",
         "\\cmidrule(lr){2-3}\\cmidrule(lr){4-6}",
         " & ARI & NMI & ARI & NMI & ASW \\\\", "\\midrule"]
    for k in [1, 3, 5, 10, 20]:
        f = f"rows/brain10x__svdq_{k}__s2024.csv"
        s = sp[f"svdq_{k}"]
        nm = f"\\textbf{{{k}}}" if k == 5 else str(k)
        L.append(" & ".join([nm,
                             f"{rowval(f,'ARI'):.3f}", f"{rowval(f,'NMI'):.3f}",
                             f"{float(s['ARI']):.3f}", f"{float(s['NMI']):.3f}", f"{float(s['ASW']):.4f}"]) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write("supp_svdq_table.tex", L)


def lambda_table():
    base = rowval("rows/brain10x__baseline__s2024.csv", "ARI")
    rows = [("$\\lambda_{\\mathrm{edge}}$ (edge recon.)", "edge"),
            ("$\\lambda_{\\mathrm{omics}}$ (feature recon.)", "gene_expr"),
            ("$\\lambda_{\\mathrm{adj}}$ (latent adj. recon.)", "adj_loss")]
    L = ["% Auto-generated by make_supp_tables.py (R3.2)",
         "\\begin{table}[ht]", "\\centering",
         "\\caption{\\textbf{\\revised{Local robustness to individual loss weights.}} "
         "\\revised{Each loss weight is scaled by $\\times0.1$ and $\\times10$ around its "
         "task setting on 10x Multiome mouse brain (real cell-type labels, single seed 2024); "
         "ARI is reported. The unperturbed baseline ARI is " + f"{base:.3f}" + ".}}",
         "\\label{tab:lambda}", "\\footnotesize",
         "\\begin{tabular}{@{}lccc@{}}", "\\toprule",
         "\\textbf{Loss weight} & ARI ($\\times0.1$) & ARI (baseline) & ARI ($\\times10$) \\\\",
         "\\midrule"]
    for name, key in rows:
        lo = rowval(f"rows/brain10x__{key}_x0.1__s2024.csv", "ARI")
        hi = rowval(f"rows/brain10x__{key}_x10.0__s2024.csv", "ARI")
        L.append(f"{name} & {lo:.3f} & {base:.3f} & {hi:.3f} \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write("supp_lambda_table.tex", L)


def mmd_table():
    m = {r["tag"]: r for r in csv.DictReader(open(os.path.join(RES, "mmd_dev_summary.csv")))}
    L = ["% Auto-generated by make_supp_tables.py (R1.2/R2.C1/R3.2)",
         "\\begin{table}[ht]", "\\centering",
         "\\caption{\\textbf{\\revised{MMD batch-alignment ablation.}} \\revised{NSCLC 1\\% "
         "multi-batch subset (7{,}017 observations, cell-type labels), \\textbf{single seed "
         "(2024)}. Enabling MMD improves cell-type clustering and batch mixing (lower batch "
         "ASW and higher kNN batch entropy indicate better mixing).}}",
         "\\label{tab:mmd}", "\\footnotesize",
         "\\begin{tabular}{@{}lcccc@{}}", "\\toprule",
         "\\textbf{Setting} & cell-type ARI & NMI & batch ASW & kNN batch entropy \\\\",
         "\\midrule"]
    names = {"baseline_no_mmd": "without MMD", "with_mmd": "with MMD"}
    for tag in ["baseline_no_mmd", "with_mmd"]:
        r = m[tag]
        L.append(" & ".join([names[tag], f"{float(r['ARI']):.3f}", f"{float(r['NMI']):.3f}",
                             f"{float(r['ASW_batch']):.3f}", f"{float(r['batch_knn_entropy']):.3f}"]) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write("supp_mmd_table.tex", L)


def main():
    ablation_table(); nsam_table(); svdq_table(); lambda_table(); mmd_table()


if __name__ == "__main__":
    main()
